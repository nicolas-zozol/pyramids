import { describe, expect, it } from 'vitest';
import {
  getArticleIndex,
  type ArticleIndexEntry,
} from '../src/content/article-index.ts';
import { urlScheme } from '../src/routing/scheme.ts';
import {
  buildUrl,
  landingPages,
  urlSet,
} from '../src/routing/url-scheme/index.ts';
import { v1UrlMap, type V1MappingRow } from '../src/routing/v1-url-map.ts';
import { redirectsFile } from './emit-redirects.mjs';

const HEADER = '# generated by scripts/emit-redirects.mjs from the v1 map';

const fileOfUrl = (url: string) =>
  url === '/' ? 'index.html' : `${url.slice(1)}.html`;

const builtFilesOf = (index: readonly ArticleIndexEntry[]) => [
  '404.html',
  'sitemap.xml',
  'assets/main.js',
  ...[...landingPages(urlScheme), ...urlSet(urlScheme, index)].map((page) =>
    fileOfUrl(buildUrl(urlScheme, page)),
  ),
];

const rulesOf = (text: string) =>
  text
    .trimEnd()
    .split('\n')
    .filter((line) => !line.startsWith('#'));

const permanent = (from: string, to: string): V1MappingRow => ({
  from,
  destination: { kind: 'permanent', to },
});
const gone = (from: string): V1MappingRow => ({
  from,
  destination: { kind: 'gone' },
});
const none = (from: string): V1MappingRow => ({
  from,
  destination: { kind: 'none', why: 'no destination' },
});

describe('redirectsFile over the v1 map of the site', () => {
  it('writes one rule per served row, the namespace rule last, with no defect', async () => {
    const index = await getArticleIndex();

    const { text, defects, summary } = redirectsFile({
      rows: v1UrlMap(urlScheme, index),
      files: builtFilesOf(index),
    });

    expect(defects).toEqual([]);
    expect(text.split('\n')[0]).toBe(HEADER);
    expect(text.trimEnd().split('\n').at(-1)).toBe('/learn/* /404.html 410');
    expect(rulesOf(text)).toHaveLength(77);
    expect(summary).toBe(
      'redirects: 77 rules (67 permanent, 5 gone, 5 not found) → dist/client/_redirects',
    );
  });

  it('serves the edge cases of the design', async () => {
    const index = await getArticleIndex();
    const rules = rulesOf(
      redirectsFile({
        rows: v1UrlMap(urlScheme, index),
        files: builtFilesOf(index),
      }).text,
    );

    expect(rules).toContain(
      '/learn/blockchain/s/provenance-des-rendements-du-yield-farming-dans-la-blockchain /fr/articles/c/blockchain/provenance-des-rendements-du-yield-farming-dans-la-blockchain 301',
    );
    expect(rules).toContain('/learn/fr/blockchain /fr/articles/c/blockchain 301');
    expect(rules).toContain('/learn/tag/DeFi /articles 301');
    expect(rules.some((rule) => rule.startsWith('/learn/tag/defi '))).toBe(false);
    expect(rules).toContain('/learn/javascript/s/es6-7.md /404.html 410');
    expect(rules).toContain('/learn/page/:n /404.html 404');
    expect(rules).toContain('/learn/tag/:tag/page/:n /404.html 404');
    expect(rules).toContain('/learn/images/:file /404.html 404');
    expect(rules).toContain('/learn/:category/s/images/:file /404.html 404');
  });

  it('retires the address of an article absent from the index, its raw markdown Gone, and the build stays green', async () => {
    const index = (await getArticleIndex()).filter(
      (entry) => entry.slug !== 'ledger-versus-metamask',
    );

    const { text, defects } = redirectsFile({
      rows: v1UrlMap(urlScheme, index),
      files: builtFilesOf(index),
    });
    const rules = rulesOf(text);

    expect(defects).toEqual([]);
    expect(
      rules.some((rule) =>
        rule.startsWith('/learn/blockchain/s/ledger-versus-metamask '),
      ),
    ).toBe(false);
    expect(rules).toContain(
      '/learn/blockchain/s/ledger-versus-metamask.md /404.html 410',
    );
  });
});

describe('redirectsFile translating a row', () => {
  const files = ['404.html', 'index.html', 'articles.html', 'fr/articles.html'];

  it('leads a permanent row to its destination in 301, a gone row to 404.html in 410, in the order of the map', () => {
    const { text } = redirectsFile({
      rows: [
        permanent('/learn', '/articles'),
        gone('/learn/old.md'),
        permanent('/learn/fr', '/fr/articles'),
      ],
      files,
    });

    expect(text).toBe(
      [
        HEADER,
        '/learn /articles 301',
        '/learn/old.md /404.html 410',
        '/learn/fr /fr/articles 301',
        '',
      ].join('\n'),
    );
  });

  it('answers 404 for a row without destination under /learn, and writes no rule for one elsewhere', () => {
    const rules = rulesOf(
      redirectsFile({
        rows: [
          none('/learn/page/:n'),
          none('/portfolio'),
          none('/prosemirror/:path*'),
          none('/'),
        ],
        files,
      }).text,
    );

    expect(rules).toEqual(['/learn/page/:n /404.html 404']);
  });

  it('copies the source in its case and turns a final /:name* into a splat', () => {
    const rules = rulesOf(
      redirectsFile({
        rows: [permanent('/learn/tag/DeFi', '/articles'), gone('/learn/:path*')],
        files,
      }).text,
    );

    expect(rules).toEqual([
      '/learn/tag/DeFi /articles 301',
      '/learn/* /404.html 410',
    ]);
  });

  it('forces no rule', () => {
    const { text } = redirectsFile({
      rows: [permanent('/learn', '/articles'), gone('/learn/:path*')],
      files,
    });

    expect(text).not.toContain('!');
  });

  it('counts the rules by status in its summary line', () => {
    const { summary } = redirectsFile({
      rows: [
        permanent('/learn', '/'),
        gone('/learn/old.md'),
        none('/learn/page/:n'),
        none('/portfolio'),
      ],
      files,
    });

    expect(summary).toBe(
      'redirects: 3 rules (1 permanent, 1 gone, 1 not found) → dist/client/_redirects',
    );
  });
});

describe('redirectsFile guarding the build', () => {
  it('names each permanent row whose destination is not a built page, and writes nothing', () => {
    const { text, defects } = redirectsFile({
      rows: [
        permanent('/learn', '/articles'),
        permanent('/learn/web', '/articles/c/web'),
        permanent('/learn/fr', '/fr/articles'),
      ],
      files: ['404.html', 'articles.html'],
    });

    expect(defects).toEqual([
      '/learn/web: destination /articles/c/web is not a built page',
      '/learn/fr: destination /fr/articles is not a built page',
    ]);
    expect(text).toBe('');
  });

  it('never takes 404.html for a destination', () => {
    const { defects } = redirectsFile({
      rows: [permanent('/learn', '/404')],
      files: ['404.html'],
    });

    expect(defects).toEqual(['/learn: destination /404 is not a built page']);
  });

  it('rejects a source no Netlify form expresses', () => {
    const { text, defects } = redirectsFile({
      rows: [none('/learn/:path*/images/:file'), gone('/learn/a*b')],
      files: ['404.html'],
    });

    expect(defects).toEqual([
      '/learn/:path*/images/:file: no Netlify form for this source',
      '/learn/a*b: no Netlify form for this source',
    ]);
    expect(text).toBe('');
  });

  it('fails without 404.html, the gone and not-found rules having no page', () => {
    const { text, defects } = redirectsFile({
      rows: [gone('/learn/:path*')],
      files: ['index.html'],
    });

    expect(defects).toEqual([
      '404.html: not built, the gone and not-found rules have no page',
    ]);
    expect(text).toBe('');
  });
});
