/**
 * Writes `dist/client/_redirects`, the v1 map translated into Netlify rules,
 * after `vite build`, which empties that directory: a permanent row in 301 to
 * its page, a gone row in 410 and a row without destination under `/learn` in
 * 404, both serving `404.html`. Fails, writing nothing, when a destination is
 * not a built page. Loads the `.ts` seams under `src` through Node type
 * stripping.
 *
 * Design: features/__done/pyramid-v2-epic/__done/restore-v1-urls/restore-v1-urls.design.md
 * Requirements: R-RESTOREV1-01, R-RESTOREV1-02, R-RESTOREV1-03, R-RESTOREV1-04, R-RESTOREV1-21, R-RESTOREV1-22, R-RESTOREV1-23
 */
import { existsSync } from 'node:fs';
import { readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HEADER = '# generated by scripts/emit-redirects.mjs from the v1 map';
const NOT_FOUND_PAGE = '404.html';
const V1_HOME = '/learn';
const FINAL_PLACEHOLDER_SPLAT = /\/:[A-Za-z]\w*\*$/;

const STATUS = { permanent: 301, gone: 410, notFound: 404 };

/** The `_redirects` of the v1 map over the files `vite build` wrote, or its defects. */
export function redirectsFile({ rows, files }) {
  const built = new Set(files);
  const rules = rows.flatMap((row) => {
    const served = servedAs(row);
    return served === undefined ? [] : [{ row, ...served }];
  });
  const defects = rules.flatMap(({ row, to }) => defectsOf(row, to, built));
  if (
    rules.some(({ to }) => to === `/${NOT_FOUND_PAGE}`) &&
    !built.has(NOT_FOUND_PAGE)
  ) {
    defects.push(
      `${NOT_FOUND_PAGE}: not built, the gone and not-found rules have no page`,
    );
  }

  const count = (status) =>
    rules.filter((rule) => rule.status === status).length;
  const lines = rules.map(
    ({ row, to, status }) => `${netlifySource(row.from)} ${to} ${status}`,
  );

  return {
    text: defects.length === 0 ? [HEADER, ...lines, ''].join('\n') : '',
    defects,
    summary: `redirects: ${rules.length} rules (${count(STATUS.permanent)} permanent, ${count(STATUS.gone)} gone, ${count(STATUS.notFound)} not found) → dist/client/_redirects`,
  };
}

function servedAs({ from, destination }) {
  switch (destination.kind) {
    case 'permanent':
      return { to: destination.to, status: STATUS.permanent };
    case 'gone':
      return { to: `/${NOT_FOUND_PAGE}`, status: STATUS.gone };
    default:
      return isUnderV1Home(from)
        ? { to: `/${NOT_FOUND_PAGE}`, status: STATUS.notFound }
        : undefined;
  }
}

function isUnderV1Home(from) {
  return from === V1_HOME || from.startsWith(`${V1_HOME}/`);
}

function defectsOf(row, to, built) {
  const defects = [];
  if (!hasNetlifyForm(row.from)) {
    defects.push(`${row.from}: no Netlify form for this source`);
  }
  if (row.destination.kind === 'permanent' && !built.has(builtFileOf(to))) {
    defects.push(`${row.from}: destination ${to} is not a built page`);
  }
  return defects;
}

function hasNetlifyForm(from) {
  const source = netlifySource(from);
  const beforeSplat = source.endsWith('/*') ? source.slice(0, -2) : source;
  return !beforeSplat.includes('*');
}

function netlifySource(from) {
  return from.replace(FINAL_PLACEHOLDER_SPLAT, '/*');
}

function builtFileOf(url) {
  if (url === '/') {
    return 'index.html';
  }
  const file = `${url.slice(1)}.html`;
  return file === NOT_FOUND_PAGE ? undefined : file;
}

async function filesUnder(directory) {
  if (!existsSync(directory)) {
    return [];
  }
  const entries = await readdir(directory, {
    recursive: true,
    withFileTypes: true,
  });
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) =>
      relative(directory, join(entry.parentPath, entry.name))
        .split(sep)
        .join('/'),
    );
}

async function main() {
  const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const source = join(app, 'src');
  const client = join(app, 'dist/client');

  const { urlScheme } = await import(join(source, 'routing/scheme.ts'));
  const { v1UrlMap } = await import(join(source, 'routing/v1-url-map.ts'));
  const { getArticleIndex } = await import(
    join(source, 'content/article-index.ts')
  );

  const { text, defects, summary } = redirectsFile({
    rows: v1UrlMap(urlScheme, await getArticleIndex()),
    files: await filesUnder(client),
  });
  if (defects.length > 0) {
    for (const defect of defects) {
      console.error(defect);
    }
    process.exit(1);
  }
  await writeFile(join(client, '_redirects'), text, 'utf8');
  console.log(summary);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  await main();
}
